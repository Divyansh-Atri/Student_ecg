import uuid
from datetime import datetime, timezone
from fastapi import APIRouter, Depends, HTTPException, Request, status
from sqlalchemy.orm import Session

from db.database import get_db, Patient, VitalsSnapshot, Alert, AuditEventType
from vitals.schemas import VitalsSnapshotInput, AlertResponse, AlertLevel, RecommendedAction
from api.middleware.auth import require_clinician_or_above, api_key_header
from agent.graph import monitoring_agent
from compliance.audit_logger import log_event
from compliance.phi_handler import deidentify

DISCLAIMER = (
    "CLINICAL DECISION SUPPORT ONLY. This output is generated by an AI system "
    "and must not replace the clinical judgment of a qualified healthcare professional. "
    "All alerts require clinical review before action is taken."
)

router = APIRouter(prefix="/vitals", tags=["Vitals"])


@router.post(
    "/snapshot",
    response_model=AlertResponse,
    status_code=status.HTTP_200_OK,
    summary="Submit a vitals snapshot for analysis",
)
def submit_vitals_snapshot(
    payload: VitalsSnapshotInput,
    request: Request,
    db: Session = Depends(get_db),
    role: str = Depends(require_clinician_or_above),
):
    api_key = request.headers.get("X-API-Key", "")

    # Ensure patient record exists
    patient = db.query(Patient).filter(Patient.patient_id == payload.patient_id).first()
    if not patient:
        patient = Patient(patient_id=payload.patient_id)
        db.add(patient)
        db.commit()

    # Persist vitals snapshot
    snapshot_id = str(uuid.uuid4())
    snapshot_record = VitalsSnapshot(
        id=snapshot_id,
        patient_id=payload.patient_id,
        systolic_bp=payload.systolic_bp,
        diastolic_bp=payload.diastolic_bp,
        heart_rate=payload.heart_rate,
        spo2=payload.spo2,
        snapshot_timestamp=payload.snapshot_timestamp,
    )
    db.add(snapshot_record)
    db.commit()

    # Run agent pipeline
    initial_state = {
        "snapshot": payload,
        "actor_role": role,
        "_db": db,
        "_api_key": api_key,
        "input_valid": False,
        "rejection_reason": None,
        "immediate_critical": False,
        "ehr_context": "",
        "ehr_available": False,
        "news2": None,
        "qsofa": None,
        "rule_alert_level": None,
        "rule_recommended_action": None,
        "llm_raw_output": None,
        "llm_available": False,
        "llm_error": None,
        "llm_output_valid": False,
        "sanitized_reasoning": None,
        "llm_confidence": None,
        "flag_for_human_review": False,
        "output_rejection_reason": None,
        "contributing_factors": None,
        "llm_limitations": None,
        "sepsis_risk_flag": False,
        "final_alert_level": None,
        "final_recommended_action": None,
        "rule_based_only": False,
        "alert_id": None,
        "snapshot_id": snapshot_id,
        "audit_logged": False,
    }

    result = monitoring_agent.invoke(initial_state)

    # Input rejected by guardrails
    if not result["input_valid"]:
        log_event(
            db=db,
            event_type=AuditEventType.INPUT_REJECTED,
            actor_role=role,
            api_key=api_key,
            patient_id=payload.patient_id,
            endpoint="/api/v1/vitals/snapshot",
            event_data={"reason": result["rejection_reason"]},
        )
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Input rejected by clinical guardrails: {result['rejection_reason']}",
        )

    # Persist alert
    alert_id = str(uuid.uuid4())
    import json
    alert_record = Alert(
        id=alert_id,
        patient_id=payload.patient_id,
        snapshot_id=snapshot_id,
        alert_level=result["final_alert_level"],
        news2_score=result["news2"].total_score,
        qsofa_score=result["qsofa"].score,
        sepsis_risk_flag=result["sepsis_risk_flag"],
        llm_reasoning=result.get("sanitized_reasoning"),
        llm_confidence=result.get("llm_confidence"),
        llm_contributing_factors=json.dumps(result.get("contributing_factors") or []),
        llm_limitations=result.get("llm_limitations"),
        recommended_action=result["final_recommended_action"],
        rule_based_only=result["rule_based_only"],
        disclaimer=DISCLAIMER,
    )
    db.add(alert_record)
    db.commit()

    return AlertResponse(
        alert_id=alert_id,
        patient_id=payload.patient_id,
        snapshot_id=snapshot_id,
        alert_level=result["final_alert_level"],
        news2=result["news2"],
        qsofa=result["qsofa"],
        sepsis_risk_flag=result["sepsis_risk_flag"],
        recommended_action=result["final_recommended_action"],
        reasoning_summary=result.get("sanitized_reasoning"),
        contributing_factors=result.get("contributing_factors"),
        llm_confidence=result.get("llm_confidence"),
        llm_limitations=result.get("llm_limitations"),
        rule_based_only=result["rule_based_only"],
        disclaimer=DISCLAIMER,
        created_at=datetime.now(timezone.utc),
    )
