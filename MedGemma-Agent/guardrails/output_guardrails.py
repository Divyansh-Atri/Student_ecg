"""
Output guardrails — evaluator gate between LLM output and the alert router.

Checks:
1. Schema enforcement  — LLM returned required fields
2. Grounding check     — reasoning references actual vital values
3. Prohibited content  — no drug names, doses, or direct treatment orders
4. Confidence check    — low confidence flagged for human review
5. Contradiction check — LLM level must not differ from rule level by > 1 tier
6. Disclaimer enforce  — mandatory disclaimer present in every output
"""

from __future__ import annotations
import re
from dataclasses import dataclass
from vitals.schemas import AlertLevel, VitalsSnapshotInput

# Alert level ordering for contradiction check
ALERT_ORDER = {
    AlertLevel.NORMAL: 0,
    AlertLevel.MEDIUM: 1,
    AlertLevel.HIGH: 2,
    AlertLevel.CRITICAL: 3,
}

# Prohibited patterns — drug names, dosing language
PROHIBITED_PATTERNS = [
    r"\b\d+\s*mg\b",                          # dosing: "10 mg"
    r"\badminister\b",
    r"\bprescribe\b",
    r"\binfuse\b",
    r"\bbolus\b",
    r"\bnorepinephrine\b", r"\bvasopressin\b", r"\bdopamine\b",
    r"\bvancomycin\b", r"\bpiperacillin\b", r"\bmeropenem\b",  # antibiotics
    r"\bintubat\b",                            # intubation
    r"\bdefibrillat\b",
]

DISCLAIMER = (
    "CLINICAL DECISION SUPPORT ONLY. This output is generated by an AI system "
    "and must not replace the clinical judgment of a qualified healthcare professional. "
    "All alerts require clinical review before action is taken."
)


@dataclass
class OutputValidationResult:
    valid: bool
    sanitized_reasoning: str | None
    confidence: float | None
    flag_for_human_review: bool
    rejection_reason: str | None
    disclaimer: str = DISCLAIMER


def validate_llm_output(
    llm_output: dict,
    rule_alert_level: AlertLevel,
    snapshot: VitalsSnapshotInput,
    min_confidence: float = 0.6,
) -> OutputValidationResult:
    """
    Validates and sanitizes the structured JSON output from MedGemma.
    Returns a sanitized reasoning string safe to surface to clinicians.
    """

    # 1. Required fields
    required = {"risk_level", "confidence", "reasoning", "sepsis_risk_flag"}
    missing = required - set(llm_output.keys())
    if missing:
        return OutputValidationResult(
            valid=False,
            sanitized_reasoning=None,
            confidence=None,
            flag_for_human_review=True,
            rejection_reason=f"LLM output missing required fields: {missing}",
        )

    reasoning: str = str(llm_output.get("reasoning", ""))
    confidence: float = float(llm_output.get("confidence", 0.0))

    # 2. Grounding check — reasoning must reference at least one actual vital value
    vital_values = [
        str(int(snapshot.systolic_bp)),
        str(int(snapshot.diastolic_bp)),
        str(int(snapshot.heart_rate)),
        str(round(snapshot.spo2, 1)),
    ]
    grounded = any(v in reasoning for v in vital_values)
    if not grounded:
        return OutputValidationResult(
            valid=False,
            sanitized_reasoning=None,
            confidence=confidence,
            flag_for_human_review=True,
            rejection_reason="LLM reasoning does not reference any provided vital values (grounding failure).",
        )

    # 3. Prohibited content
    for pattern in PROHIBITED_PATTERNS:
        if re.search(pattern, reasoning, re.IGNORECASE):
            return OutputValidationResult(
                valid=False,
                sanitized_reasoning=None,
                confidence=confidence,
                flag_for_human_review=True,
                rejection_reason=f"LLM output contains prohibited clinical content (matched: {pattern}).",
            )

    # 4. Contradiction check
    try:
        llm_level = AlertLevel(llm_output["risk_level"])
    except ValueError:
        return OutputValidationResult(
            valid=False,
            sanitized_reasoning=None,
            confidence=confidence,
            flag_for_human_review=True,
            rejection_reason=f"LLM returned unknown risk_level: {llm_output.get('risk_level')}",
        )

    level_diff = abs(ALERT_ORDER[llm_level] - ALERT_ORDER[rule_alert_level])
    if level_diff > 1:
        return OutputValidationResult(
            valid=False,
            sanitized_reasoning=None,
            confidence=confidence,
            flag_for_human_review=True,
            rejection_reason=(
                f"LLM alert level ({llm_level}) contradicts rule-based level "
                f"({rule_alert_level}) by {level_diff} tiers (max allowed: 1)."
            ),
        )

    # 5. Confidence threshold
    flag_for_review = confidence < min_confidence

    # 6. Strip thinking tokens and sanitize
    sanitized = _strip_thinking_tokens(reasoning).strip()

    return OutputValidationResult(
        valid=True,
        sanitized_reasoning=sanitized,
        confidence=confidence,
        flag_for_human_review=flag_for_review,
        rejection_reason=None,
    )


def _strip_thinking_tokens(text: str) -> str:
    """Remove Gemma 3 internal thinking tokens from LLM output."""
    # Remove <unused94>...</unused95> thinking blocks
    text = re.sub(r"<unused94>.*?<unused95>", "", text, flags=re.DOTALL)
    # Remove any other leftover unused tokens
    text = re.sub(r"<unused\d+>", "", text)
    return text.strip()
